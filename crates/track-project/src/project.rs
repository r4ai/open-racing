impl Project {
    /// A new project with the built-in surfaces and materials and a small oval to start
    /// from.
    pub fn new(name: &str) -> Self {
        let surfaces = crate::builtin::surfaces();
        let materials = crate::builtin::materials();
        let s = |name: &str| name.to_string();
        let m = s;
        // A rounded rectangle, 600 m × 250 m, driven anticlockwise.
        let nodes = [
            (0.0, 0.0),
            (250.0, 0.0),
            (420.0, 20.0),
            (480.0, 130.0),
            (420.0, 240.0),
            (250.0, 260.0),
            (0.0, 260.0),
            (-120.0, 200.0),
            (-150.0, 130.0),
            (-120.0, 60.0),
        ]
        .map(|(x, y)| Node::at(x, y, 0.0))
        .to_vec();
        // Kerbs through the corners.
        let corners = vec![Range { from: 1.6, to: 4.4 }, Range { from: 6.6, to: 9.4 }];
        let kerb = Strip {
            name: "kerb".into(),
            width: 1.2,
            surface: s("kerb"),
            material: m("kerb"),
            profile: Profile::Crown(0.03),
            ranges: corners,
            fade: 4.0,
        };
        let grass = |width| Strip {
            name: "grass".into(),
            width,
            surface: s("grass"),
            material: m("grass"),
            profile: Profile::Slope(0.3),
            ranges: vec![],
            fade: 0.0,
        };
        let barrier = |side| Barrier {
            name: "wall".into(),
            side,
            offset: 20.0,
            height: 1.0,
            thickness: 0.5,
            material: m("concrete"),
            ranges: vec![],
        };
        let road = Road {
            name: "circuit".into(),
            closed: true,
            nodes,
            width_left: StationCurve::constant(6.0),
            width_right: StationCurve::constant(6.0),
            bank: StationCurve::constant(0.0),
            crown: 0.05,
            surface: s("asphalt"),
            material: m("asphalt"),
            left: vec![kerb.clone(), grass(18.0)],
            right: vec![kerb, grass(18.0)],
            lines: [("left edge", 5.7), ("right edge", -5.7)]
                .map(|(name, offset)| PaintLine {
                    name: name.into(),
                    offset,
                    width: 0.12,
                    material: m("paint"),
                    ranges: vec![],
                    dash: None,
                })
                .to_vec(),
            barriers: vec![barrier(Side::Left), barrier(Side::Right)],
            resolution: 2.0,
        };
        Self {
            format: FORMAT_VERSION,
            name: name.into(),
            terrain: Terrain {
                enabled: true,
                surface: s("grass"),
                material: m("grass"),
                margin: 200.0,
                cell: 8.0,
            },
            surfaces,
            materials,
            roads: vec![road],
            splines: vec![],
            props: vec![],
            main_road: "circuit".into(),
            markers: Markers {
                start: 0.5,
                sectors: vec![3.0, 6.5],
                grid: Grid {
                    count: 12,
                    spacing: 8.0,
                    stagger: 2.5,
                    behind: 10.0,
                    pole: Side::Left,
                },
                pit: None,
            },
        }
    }

    pub fn load(dir: &Path) -> Result<Self, Error> {
        let path = dir.join(PROJECT_FILE);
        let src = std::fs::read_to_string(&path).map_err(|e| Error::Io(path.clone(), e))?;
        let project: Self =
            ron::from_str(&src).map_err(|e| Error::Parse(path.clone(), Box::new(e)))?;
        if project.format != FORMAT_VERSION {
            return Err(Error::Invalid(format!(
                "{}: format version {}, expected {FORMAT_VERSION}",
                path.display(),
                project.format
            )));
        }
        project.validate()?;
        Ok(project)
    }

    pub fn save(&self, dir: &Path) -> Result<(), Error> {
        std::fs::create_dir_all(dir).map_err(|e| Error::Io(dir.to_path_buf(), e))?;
        let src = ron::ser::to_string_pretty(self, ron::ser::PrettyConfig::default())
            .expect("project serialises");
        let path = dir.join(PROJECT_FILE);
        std::fs::write(&path, src).map_err(|e| Error::Io(path, e))
    }

    /// Checks that every name refers to something that exists and the main road can be
    /// a circuit.
    pub fn validate(&self) -> Result<(), Error> {
        let invalid = |msg: String| Err(Error::Invalid(msg));
        for (what, names) in [
            (
                "road or spline",
                self.roads
                    .iter()
                    .map(|r| &r.name)
                    .chain(self.splines.iter().map(|s| &s.name))
                    .collect::<Vec<_>>(),
            ),
            ("surface", self.surfaces.iter().map(|s| &s.name).collect()),
            ("prop", self.props.iter().map(|p| &p.name).collect()),
            ("material", self.materials.iter().map(|m| &m.name).collect()),
        ] {
            for (i, n) in names.iter().enumerate() {
                if names[..i].contains(n) {
                    return invalid(format!("two {what}s are named \"{n}\""));
                }
            }
        }
        let Some(main) = self.road(&self.main_road) else {
            return invalid(format!(
                "the main road \"{}\" does not exist",
                self.main_road
            ));
        };
        if !main.closed || main.nodes.len() < 3 {
            return invalid(format!(
                "the main road \"{}\" must be a closed loop of at least 3 nodes",
                main.name
            ));
        }
        for r in &self.roads {
            let strips = r.left.iter().chain(&r.right);
            let surfaces = std::iter::once(&r.surface).chain(strips.clone().map(|s| &s.surface));
            let materials = [&r.material]
                .into_iter()
                .chain(strips.map(|s| &s.material))
                .chain(r.lines.iter().map(|l| &l.material))
                .chain(r.barriers.iter().map(|b| &b.material));
            for s in surfaces {
                if self.surface_index(s).is_none() {
                    return invalid(format!("road \"{}\": no surface named \"{s}\"", r.name));
                }
            }
            for m in materials {
                if self.material_index(m).is_none() {
                    return invalid(format!("road \"{}\": no material named \"{m}\"", r.name));
                }
            }
            if r.nodes.len() < 2 {
                return invalid(format!("road \"{}\" needs at least 2 nodes", r.name));
            }
            if r.nodes
                .iter()
                .any(|n| !n.pos.is_finite() || !n.handles.is_valid())
            {
                return invalid(format!("road \"{}\": invalid node or handle", r.name));
            }
            for (name, curve) in [
                ("left width", &r.width_left),
                ("right width", &r.width_right),
                ("bank", &r.bank),
            ] {
                if curve.keys.is_empty()
                    || curve.keys.iter().any(|k| {
                        !k.u.is_finite()
                            || !k.value.is_finite()
                            || !k.slope_in.is_finite()
                            || !k.slope_out.is_finite()
                    })
                {
                    return invalid(format!("road \"{}\": {name} has an invalid key", r.name));
                }
            }
            if r.resolution < 0.25 {
                return invalid(format!("road \"{}\": resolution under 0.25 m", r.name));
            }
            if r.left.iter().chain(&r.right).any(|s| s.width < 0.0) {
                return invalid(format!("road \"{}\": a strip has a negative width", r.name));
            }
        }
        for sp in &self.splines {
            let invalid = |what: &str| invalid(format!("spline \"{}\": {what}", sp.name));
            if let Shape::Band { surface, width, .. } = &sp.shape {
                if self.surface_index(surface).is_none() {
                    return invalid(&format!("no surface named \"{surface}\""));
                }
                if *width < 0.0 {
                    return invalid("negative width");
                }
            }
            if self.material_index(sp.material()).is_none() {
                return invalid(&format!("no material named \"{}\"", sp.material()));
            }
            if sp.nodes.len() < 2 {
                return invalid("needs at least 2 nodes");
            }
            if sp
                .nodes
                .iter()
                .any(|n| !n.pos.is_finite() || !n.handles.is_valid())
            {
                return invalid("invalid node or handle");
            }
            if sp.resolution < 0.1 {
                return invalid("resolution under 0.1 m");
            }
        }
        for p in &self.props {
            if p.scale.is_nan() || p.scale <= 0.0 {
                return invalid(format!("prop \"{}\": scale must be positive", p.name));
            }
        }
        if let Some(p) = &self.markers.pit
            && (self.road(&p.road).is_none() || p.road == self.main_road)
        {
            return invalid(format!(
                "the pit lane \"{}\" must be a road other than the main road",
                p.road
            ));
        }
        if self.surface_index(&self.terrain.surface).is_none()
            || self.material_index(&self.terrain.material).is_none()
        {
            return invalid("terrain: undefined surface or material".into());
        }
        Ok(())
    }

    pub fn road_index(&self, name: &str) -> Option<usize> {
        self.roads.iter().position(|r| r.name == name)
    }

    pub fn road(&self, name: &str) -> Option<&Road> {
        self.roads.iter().find(|r| r.name == name)
    }

    pub fn spline(&self, name: &str) -> Option<&Spline> {
        self.splines.iter().find(|s| s.name == name)
    }

    /// Nodes of the road or spline named `name`, and whether it is closed.
    pub fn line(&self, name: &str) -> Option<(&[Node], bool)> {
        self.road(name)
            .map(|r| (r.nodes.as_slice(), r.closed))
            .or_else(|| self.spline(name).map(|s| (s.nodes.as_slice(), s.closed)))
    }

    pub fn surface_index(&self, name: &str) -> Option<usize> {
        self.surfaces.iter().position(|s| s.name == name)
    }

    pub fn material_index(&self, name: &str) -> Option<usize> {
        self.materials.iter().position(|m| m.name == name)
    }

    /// Index of the main road; the project must be valid.
    pub fn main_index(&self) -> usize {
        self.road_index(&self.main_road)
            .expect("the main road exists")
    }

    /// Surface of the built-in kind, if the project has one.
    pub fn surface_of(&self, kind: Surface) -> Option<&str> {
        self.surfaces
            .iter()
            .find(|s| s.props.kind == kind)
            .map(|s| s.name.as_str())
    }
}
