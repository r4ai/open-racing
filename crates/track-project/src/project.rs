use crate::Error;

/// Version of `project.ron`.
pub const FORMAT_VERSION: u32 = 2;
pub const PROJECT_FILE: &str = "project.ron";

/// Name of an entry of `Project::surfaces`.
pub type SurfaceId = String;
/// Name of an entry of `Project::materials`.
pub type MaterialId = String;

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Project {
    pub format: u32,
    pub name: String,
    pub surfaces: Vec<NamedSurface>,
    pub materials: Vec<MaterialDef>,
    pub roads: Vec<Road>,
    /// Kerbs, walls and fences placed on their own, apart from any road.
    #[serde(default)]
    pub splines: Vec<Spline>,
    /// 3D models placed in the scene: grandstands, signs, trees, buildings.
    #[serde(default)]
    pub props: Vec<Prop>,
    /// Name of the circuit: the closed road the centreline, timing and grid follow.
    pub main_road: String,
    pub markers: Markers,
    pub terrain: Terrain,
}

/// Physical properties of a surface, with a name for the editor.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct NamedSurface {
    pub name: String,
    pub props: SurfaceProps,
}

/// A tiled, tinted texture with dielectric PBR parameters.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct MaterialDef {
    pub name: String,
    /// sRGB tint multiplied with the texture.
    pub color: [f32; 3],
    pub texture: TextureSource,
    /// Metres one repetition of the texture covers: across and along a road.
    pub tile: [f32; 2],
    pub roughness: f32,
    pub reflectance: f32,
    /// Render back faces too (thin barriers and fences).
    #[serde(default)]
    pub double_sided: bool,
    /// A tangent-space normal map, tiled as the texture.
    #[serde(default)]
    pub normal: TextureSource,
    /// What the texture's alpha does.
    #[serde(default)]
    pub alpha: Alpha,
}

/// How a material's alpha is used.
#[derive(Clone, Copy, Debug, Default, PartialEq, Serialize, Deserialize)]
pub enum Alpha {
    /// Ignored.
    #[default]
    Opaque,
    /// Cut out below this value, as for fences and foliage.
    Mask(f32),
    /// Blended, as for glass.
    Blend,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum TextureSource {
    /// Plain colour.
    #[default]
    None,
    /// A texture generated by the tool.
    Builtin(BuiltinTexture),
    /// A PNG or DDS file, relative to the project's directory.
    File(PathBuf),
}

