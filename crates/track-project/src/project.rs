/// A kind of wall, guard rail, fence or tyre stack, made once and put along roads and
/// splines.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct WallStyle {
    pub name: String,
    pub height: f64,
    /// 0 for a thin rail or fence.
    pub thickness: f64,
    pub material: MaterialId,
    /// A model repeated along it instead of its plain shape.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub model: Option<ModelRun>,
}

impl StripStyle {
    /// A strip of this type.
    pub fn strip(&self, name: &str, ranges: Vec<Range>) -> Strip {
        Strip {
            name: name.to_string(),
            width: self.width,
            surface: self.surface.clone(),
            material: self.material.clone(),
            profile: self.profile.clone(),
            ranges,
            fade: self.fade,
            style: Some(self.name.clone()),
            corner: None,
        }
    }

    /// Gives a strip of this type its look and feel; its width stays its own.
    pub fn restyle(&self, s: &mut Strip) {
        s.surface = self.surface.clone();
        s.material = self.material.clone();
        s.profile = self.profile.clone();
        s.fade = self.fade;
        s.style = Some(self.name.clone());
    }
}

impl WallStyle {
    /// A barrier of this type.
    pub fn barrier(&self, name: &str, side: Side, offset: f64, ranges: Vec<Range>) -> Barrier {
        let mut b = Barrier {
            name: name.to_string(),
            side,
            offset,
            height: 0.0,
            thickness: 0.0,
            material: String::new(),
            ranges,
            model: None,
            style: None,
            corner: None,
        };
        self.restyle(&mut b);
        b
    }

    /// Gives a barrier of this type its shape and look; its place stays its own.
    pub fn restyle(&self, b: &mut Barrier) {
        b.height = self.height;
        b.thickness = self.thickness;
        b.material = self.material.clone();
        b.model = self.model.clone();
        b.style = Some(self.name.clone());
    }
}

/// A 3D model repeated along a wall in place of its plain shape: a tyre stack, a
/// section of guard rail, a fence panel. The model's +X runs along the wall, its +Z is
/// up and its +Y faces the road (a spline's left); its origin sits on the wall's line.
/// Cars still collide with the wall's plain shape.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct ModelRun {
    /// A glTF file (.glb or .gltf), relative to the project's directory.
    pub model: PathBuf,
    /// Length of each copy along the wall, m; 0 takes the model's own. Copies stretch a
    /// little so that a whole number of them fill each stretch.
    #[serde(default)]
    pub length: f64,
    /// Bend each copy along the line (else each stands straight, on its middle).
    #[serde(default = "yes")]
    pub bend: bool,
    /// Turn it round, facing away from the road.
    #[serde(default)]
    pub flip: bool,
}

/// Which part of a corner a strip or barrier laid round it is.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum CornerPart {
    /// On the outside where cars turn in.
    Entry,
    /// On the inside round the apex.
    Apex,
    /// On the outside where cars run out.
    Exit,
    /// The whole outside, from before the entry to well past the exit: a gravel trap,
    /// run-off, a tyre wall.
    Outside,
}

impl CornerPart {
    pub const ALL: [CornerPart; 4] = [
        CornerPart::Entry,
        CornerPart::Apex,
        CornerPart::Exit,
        CornerPart::Outside,
    ];

    pub fn label(self) -> &'static str {
        match self {
            CornerPart::Entry => "entry",
            CornerPart::Apex => "apex",
            CornerPart::Exit => "exit",
            CornerPart::Outside => "outside",
        }
    }
}

