/// How the two Bézier handles at a node relate to one another.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum HandleMode {
    #[default]
    Auto,
    /// Opposite directions, with independently adjustable lengths.
    Aligned,
    /// Independently adjustable directions and lengths.
    Free,
}

/// The two handles of a road or spline node.
#[derive(Clone, Copy, Debug, Default, PartialEq, Serialize, Deserialize)]
pub enum NodeHandles {
    #[default]
    Auto,
    Aligned {
        outgoing: DVec3,
        incoming_length: f64,
    },
    Free {
        incoming: DVec3,
        outgoing: DVec3,
    },
}

impl NodeHandles {
    pub fn is_auto(&self) -> bool {
        matches!(self, Self::Auto)
    }

    pub fn mode(self) -> HandleMode {
        match self {
            Self::Auto => HandleMode::Auto,
            Self::Aligned { .. } => HandleMode::Aligned,
            Self::Free { .. } => HandleMode::Free,
        }
    }

    pub fn from_offsets(mode: HandleMode, incoming: DVec3, outgoing: DVec3) -> Self {
        match mode {
            HandleMode::Auto => Self::Auto,
            HandleMode::Aligned => Self::Aligned {
                outgoing,
                incoming_length: incoming.length(),
            },
            HandleMode::Free => Self::Free { incoming, outgoing },
        }
    }

    pub fn is_valid(self) -> bool {
        match self {
            Self::Auto => true,
            Self::Aligned {
                outgoing,
                incoming_length,
            } => {
                outgoing.is_finite()
                    && incoming_length.is_finite()
                    && incoming_length >= 0.0
                    && (outgoing.length_squared() > 1e-12 || incoming_length == 0.0)
            }
            Self::Free { incoming, outgoing } => incoming.is_finite() && outgoing.is_finite(),
        }
    }
}

/// A control point of a road or spline.
#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
pub struct Node {
    pub pos: DVec3,
    #[serde(default, skip_serializing_if = "NodeHandles::is_auto")]
    pub handles: NodeHandles,
}

impl Node {
    pub fn new(pos: DVec3) -> Self {
        Self {
            pos,
            handles: NodeHandles::Auto,
        }
    }

    pub fn at(x: f64, y: f64, z: f64) -> Self {
        Self::new(DVec3::new(x, y, z))
    }
}

/// A value that varies along a road: keys at spline parameters, eased between them. A
/// closed road's value eases from the last key round to the first.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct StationCurve {
    pub keys: Vec<Key>,
}

#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
pub struct Key {
    pub u: f64,
    pub value: f64,
    /// Value change per unit of spline parameter on either side of this key.
    #[serde(default)]
    pub slope_in: f64,
    #[serde(default)]
    pub slope_out: f64,
}

impl Key {
    pub fn new(u: f64, value: f64) -> Self {
        Self {
            u,
            value,
            slope_in: 0.0,
            slope_out: 0.0,
        }
    }
}

impl StationCurve {
    pub fn constant(value: f64) -> Self {
        Self {
            keys: vec![Key::new(0.0, value)],
        }
    }

    /// The value at `u` on a road whose parameter runs over [0, `period`); closed roads
    /// wrap round, open ones hold their end values.
    pub fn eval(&self, u: f64, period: f64, closed: bool) -> f64 {
        let keys = &self.keys;
        let Some(first) = keys.first() else {
            return 0.0;
        };
        if keys.len() == 1 {
            return first.value;
        }
        // Keys are kept sorted by `u`.
        let last = keys[keys.len() - 1];
        let ease = |a: &Key, b: &Key, u: f64, span: f64| {
            let t = if span > 0.0 {
                (u / span).clamp(0.0, 1.0)
            } else {
                0.0
            };
            let (m0, m1) = (a.slope_out, b.slope_in);
            if m0 == 0.0 && m1 == 0.0 {
                return a.value + (b.value - a.value) * t * t * (3.0 - 2.0 * t);
            }
            let t2 = t * t;
            let t3 = t2 * t;
            (2.0 * t3 - 3.0 * t2 + 1.0) * a.value
                + (t3 - 2.0 * t2 + t) * span * m0
                + (-2.0 * t3 + 3.0 * t2) * b.value
                + (t3 - t2) * span * m1
        };
        if u < first.u || u >= last.u {
            if !closed {
                return if u < first.u { first.value } else { last.value };
            }
            let span = first.u + period - last.u;
            let from = if u >= last.u {
                u - last.u
            } else {
                u + period - last.u
            };
            return ease(&last, first, from, span);
        }
        let i = keys.partition_point(|k| k.u <= u) - 1;
        let (a, b) = (&keys[i], &keys[i + 1]);
        ease(a, b, u - a.u, b.u - a.u)
    }

    /// Sets the value at `u`, adding a key or moving the one already there.
    pub fn set(&mut self, u: f64, value: f64) {
        match self.keys.iter_mut().find(|k| (k.u - u).abs() < 1e-6) {
            Some(k) => k.value = value,
            None => {
                self.keys.push(Key::new(u, value));
                self.keys.sort_by(|a, b| a.u.total_cmp(&b.u));
            }
        }
    }
}

/// A stretch of road between two spline parameters. On a closed road `from > to` wraps
/// through the start.
#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
pub struct Range {
    pub from: f64,
    pub to: f64,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum Side {
    Left,
    Right,
}

impl Side {
    /// +1 to the left, −1 to the right.
    pub fn sign(self) -> f64 {
        match self {
            Self::Left => 1.0,
            Self::Right => -1.0,
        }
    }
}

/// Cross-section shape of a strip, from its inner to its outer edge.
#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
pub enum Profile {
    /// Continues the plane of what is inside it.
    Flat,
    /// A rounded crown this high (m) in the middle, as on a kerb.
    Crown(f64),
    /// Falls (or rises, negative) this far (m) to the outer edge.
    Slope(f64),
}

/// A band alongside the road: kerb, run-off, gravel trap, grass verge.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Strip {
    pub name: String,
    pub width: f64,
    pub surface: SurfaceId,
    pub material: MaterialId,
    pub profile: Profile,
    /// Where the strip is; everywhere when empty.
    #[serde(default)]
    pub ranges: Vec<Range>,
    /// Metres over which it narrows to nothing at the ends of its ranges.
    #[serde(default)]
    pub fade: f64,
}

/// A painted line on the road, drawn only: it does not change the surface.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct PaintLine {
    pub name: String,
    /// Lateral offset of its middle from the road's centre, m, positive to the left.
    pub offset: f64,
    pub width: f64,
    pub material: MaterialId,
    #[serde(default)]
    pub ranges: Vec<Range>,
    /// Painted and gap lengths of a dashed line, m.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub dash: Option<(f64, f64)>,
}

/// A wall, guard rail or fence the cars collide with.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Barrier {
    pub name: String,
    pub side: Side,
    /// Distance from the road's edge, m.
    pub offset: f64,
    pub height: f64,
    /// 0 for a thin rail or fence.
    pub thickness: f64,
    pub material: MaterialId,
    #[serde(default)]
    pub ranges: Vec<Range>,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Road {
    pub name: String,
    pub closed: bool,
    pub nodes: Vec<Node>,
    /// Distances from the road's centre to its edges, m.
    pub width_left: StationCurve,
    pub width_right: StationCurve,
    /// Banking in radians; positive raises the right edge, as for a left-hand corner.
    pub bank: StationCurve,
    /// Height of the road's centre above its edges, m, for drainage.
    pub crown: f64,
    pub surface: SurfaceId,
    pub material: MaterialId,
    /// Strips outside each edge, from the road outwards.
    pub left: Vec<Strip>,
    pub right: Vec<Strip>,
    pub lines: Vec<PaintLine>,
    pub barriers: Vec<Barrier>,
    /// Spacing of the cross-sections the road is built from, m.
    pub resolution: f64,
}

impl Road {
    /// Number of spline segments.
    pub fn segments(&self) -> usize {
        crate::curve::segments(self.nodes.len(), self.closed)
    }

    /// Range of the spline parameter: [0, period].
    pub fn period(&self) -> f64 {
        self.segments() as f64
    }

    pub fn strips(&self, side: Side) -> &Vec<Strip> {
        match side {
            Side::Left => &self.left,
            Side::Right => &self.right,
        }
    }

    /// Inserts a node before `index`, keeping keys and ranges where they were on the
    /// road.
    pub fn insert_node(&mut self, index: usize, node: Node) {
        self.nodes.insert(index, node);
        self.shift_params(index as f64 - 1.0, 1.0);
    }

    /// Removes a node, keeping keys and ranges where they were on the road as far as
    /// possible.
    pub fn remove_node(&mut self, index: usize) {
        self.nodes.remove(index);
        self.shift_params(index as f64, -1.0);
    }

    /// Moves every parameter beyond `after` by `by`.
    fn shift_params(&mut self, after: f64, by: f64) {
        let period = self.period().max(1.0);
        let shift = |u: &mut f64| {
            if *u > after {
                *u = (*u + by).clamp(0.0, period);
            }
        };
        for c in [&mut self.width_left, &mut self.width_right, &mut self.bank] {
            c.keys.iter_mut().for_each(|k| shift(&mut k.u));
        }
        let ranges = self
            .left
            .iter_mut()
            .chain(self.right.iter_mut())
            .flat_map(|s| s.ranges.iter_mut())
            .chain(self.barriers.iter_mut().flat_map(|b| b.ranges.iter_mut()))
            .chain(self.lines.iter_mut().flat_map(|l| l.ranges.iter_mut()));
        for r in ranges {
            shift(&mut r.from);
            shift(&mut r.to);
        }
    }
}

/// Which side of its line a spline's band lies on, looking along the line.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum Align {
    #[default]
    Center,
    Left,
    Right,
}

/// What a spline is built into.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub enum Shape {
    /// A drivable band along the line: a kerb, a patch of run-off, a painted area.
    Band {
        width: f64,
        #[serde(default)]
        align: Align,
        /// Cross-section from its right edge to its left.
        profile: Profile,
        surface: SurfaceId,
        material: MaterialId,
        /// Height above the ground or the nodes, m, so that it shows over what is under.
        #[serde(default)]
        lift: f64,
    },
    /// A wall, guard rail or fence standing on the line.
    Wall {
        height: f64,
        /// 0 for a thin rail or fence.
        thickness: f64,
        material: MaterialId,
        /// Whether cars collide with it.
        #[serde(default = "yes")]
        collide: bool,
    },
}

fn yes() -> bool {
    true
}

/// A kerb, wall or fence along its own spline, placed anywhere.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Spline {
    pub name: String,
    pub closed: bool,
    pub nodes: Vec<Node>,
    /// Follow the roads and the terrain under the line instead of the nodes' heights.
    pub drape: bool,
    pub shape: Shape,
    /// Spacing of the cross-sections it is built from, m.
    pub resolution: f64,
}

impl Spline {
    pub fn material(&self) -> &str {
        match &self.shape {
            Shape::Band { material, .. } | Shape::Wall { material, .. } => material,
        }
    }
}

