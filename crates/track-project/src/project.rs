/// How the two Bézier handles at a node relate to one another.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum HandleMode {
    #[default]
    Auto,
    /// Opposite directions, with independently adjustable lengths.
    Aligned,
    /// Independently adjustable directions and lengths.
    Free,
}

/// The two handles of a road or spline node.
#[derive(Clone, Copy, Debug, Default, PartialEq, Serialize, Deserialize)]
pub enum NodeHandles {
    #[default]
    Auto,
    Aligned {
        outgoing: DVec3,
        incoming_length: f64,
    },
    Free {
        incoming: DVec3,
        outgoing: DVec3,
    },
}

impl NodeHandles {
    pub fn is_auto(&self) -> bool {
        matches!(self, Self::Auto)
    }

    pub fn mode(self) -> HandleMode {
        match self {
            Self::Auto => HandleMode::Auto,
            Self::Aligned { .. } => HandleMode::Aligned,
            Self::Free { .. } => HandleMode::Free,
        }
    }

    /// The handles with their offsets put through `f`, a turn or a scaling of the node's
    /// surroundings; automatic ones follow by themselves.
    pub fn map(self, f: impl Fn(DVec3) -> DVec3) -> Self {
        match self {
            Self::Auto => Self::Auto,
            Self::Aligned {
                outgoing,
                incoming_length,
            } => Self::Aligned {
                outgoing: f(outgoing),
                incoming_length: f(-outgoing.normalize_or_zero() * incoming_length).length(),
            },
            Self::Free { incoming, outgoing } => Self::Free {
                incoming: f(incoming),
                outgoing: f(outgoing),
            },
        }
    }

    /// The mode and both offsets, as `Op::SetNodeHandles` takes them; zero for
    /// automatic handles.
    pub fn offsets(self) -> (HandleMode, DVec3, DVec3) {
        match self {
            Self::Auto => (HandleMode::Auto, DVec3::ZERO, DVec3::ZERO),
            Self::Aligned {
                outgoing,
                incoming_length,
            } => (
                HandleMode::Aligned,
                -outgoing.normalize_or_zero() * incoming_length,
                outgoing,
            ),
            Self::Free { incoming, outgoing } => (HandleMode::Free, incoming, outgoing),
        }
    }

    /// The handles reversed, for a line driven the other way: incoming and outgoing
    /// swap.
    pub fn reversed(self) -> Self {
        match self {
            Self::Auto => Self::Auto,
            Self::Aligned {
                outgoing,
                incoming_length,
            } => Self::Aligned {
                outgoing: -outgoing.normalize_or_zero() * incoming_length,
                incoming_length: outgoing.length(),
            },
            Self::Free { incoming, outgoing } => Self::Free {
                incoming: outgoing,
                outgoing: incoming,
            },
        }
    }

    pub fn from_offsets(mode: HandleMode, incoming: DVec3, outgoing: DVec3) -> Self {
        match mode {
            HandleMode::Auto => Self::Auto,
            HandleMode::Aligned => Self::Aligned {
                outgoing,
                incoming_length: incoming.length(),
            },
            HandleMode::Free => Self::Free { incoming, outgoing },
        }
    }

    pub fn is_valid(self) -> bool {
        match self {
            Self::Auto => true,
            Self::Aligned {
                outgoing,
                incoming_length,
            } => {
                outgoing.is_finite()
                    && incoming_length.is_finite()
                    && incoming_length >= 0.0
                    && (outgoing.length_squared() > 1e-12 || incoming_length == 0.0)
            }
            Self::Free { incoming, outgoing } => incoming.is_finite() && outgoing.is_finite(),
        }
    }
}

/// A control point of a road or spline.
#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
pub struct Node {
    pub pos: DVec3,
    #[serde(default, skip_serializing_if = "NodeHandles::is_auto")]
    pub handles: NodeHandles,
}

impl Node {
    pub fn new(pos: DVec3) -> Self {
        Self {
            pos,
            handles: NodeHandles::Auto,
        }
    }

    pub fn at(x: f64, y: f64, z: f64) -> Self {
        Self::new(DVec3::new(x, y, z))
    }
}

/// A value that varies along a road: keys at spline parameters, eased between them. A
/// closed road's value eases from the last key round to the first.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct StationCurve {
    pub keys: Vec<Key>,
}

#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
pub struct Key {
    pub u: f64,
    pub value: f64,
    /// Value change per unit of spline parameter on either side of this key.
    #[serde(default)]
    pub slope_in: f64,
    #[serde(default)]
    pub slope_out: f64,
}

impl Key {
    pub fn new(u: f64, value: f64) -> Self {
        Self {
            u,
            value,
            slope_in: 0.0,
            slope_out: 0.0,
        }
    }
}

impl StationCurve {
    pub fn constant(value: f64) -> Self {
        Self {
            keys: vec![Key::new(0.0, value)],
        }
    }

    /// The value at `u` on a road whose parameter runs over [0, `period`); closed roads
    /// wrap round, open ones hold their end values.
    pub fn eval(&self, u: f64, period: f64, closed: bool) -> f64 {
        let keys = &self.keys;
        let Some(first) = keys.first() else {
            return 0.0;
        };
        if keys.len() == 1 {
            return first.value;
        }
        // Keys are kept sorted by `u`.
        let last = keys[keys.len() - 1];
        let ease = |a: &Key, b: &Key, u: f64, span: f64| {
            let t = if span > 0.0 {
                (u / span).clamp(0.0, 1.0)
            } else {
                0.0
            };
            let (m0, m1) = (a.slope_out, b.slope_in);
            if m0 == 0.0 && m1 == 0.0 {
                return a.value + (b.value - a.value) * t * t * (3.0 - 2.0 * t);
            }
            let t2 = t * t;
            let t3 = t2 * t;
            (2.0 * t3 - 3.0 * t2 + 1.0) * a.value
                + (t3 - 2.0 * t2 + t) * span * m0
                + (-2.0 * t3 + 3.0 * t2) * b.value
                + (t3 - t2) * span * m1
        };
        if u < first.u || u >= last.u {
            if !closed {
                return if u < first.u { first.value } else { last.value };
            }
            let span = first.u + period - last.u;
            let from = if u >= last.u {
                u - last.u
            } else {
                u + period - last.u
            };
            return ease(&last, first, from, span);
        }
        let i = keys.partition_point(|k| k.u <= u) - 1;
        let (a, b) = (&keys[i], &keys[i + 1]);
        ease(a, b, u - a.u, b.u - a.u)
    }

    /// Sets the value at `u`, adding a key or moving the one already there.
    pub fn set(&mut self, u: f64, value: f64) {
        match self.keys.iter_mut().find(|k| (k.u - u).abs() < 1e-6) {
            Some(k) => k.value = value,
            None => {
                self.keys.push(Key::new(u, value));
                self.keys.sort_by(|a, b| a.u.total_cmp(&b.u));
            }
        }
    }
}

/// A stretch of road between two spline parameters. On a closed road `from > to` wraps
/// through the start.
#[derive(Clone, Copy, Debug, PartialEq, Serialize, Deserialize)]
pub struct Range {
    pub from: f64,
    pub to: f64,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum Side {
    Left,
    Right,
}

impl Side {
    /// +1 to the left, −1 to the right.
    pub fn sign(self) -> f64 {
        match self {
            Self::Left => 1.0,
            Self::Right => -1.0,
        }
    }

    pub fn other(self) -> Self {
        match self {
            Self::Left => Self::Right,
            Self::Right => Self::Left,
        }
    }
}

/// Cross-section shape of a strip, from its inner to its outer edge.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub enum Profile {
    /// Continues the plane of what is inside it.
    Flat,
    /// A rounded crown this high (m) in the middle, as on a kerb.
    Crown(f64),
    /// Falls (or rises, negative) this far (m) to the outer edge.
    Slope(f64),
    /// Any shape: heights (m) at fractions (0 to 1) of the way across, in order, joined
    /// by straight lines; before the first and after the last, their heights. A
    /// stepped, saw-tooth or double-hump kerb.
    Shape(Vec<[f64; 2]>),
}

impl Profile {
    /// Height above its inner edge at `x` of the way across.
    pub fn height(&self, x: f64) -> f64 {
        match self {
            Profile::Flat => 0.0,
            Profile::Crown(h) => h * (std::f64::consts::PI * x).sin(),
            Profile::Slope(drop) => -drop * x,
            Profile::Shape(points) => {
                let i = points.partition_point(|p| p[0] <= x);
                match (points.get(i.wrapping_sub(1)), points.get(i)) {
                    (Some(a), Some(b)) if b[0] - a[0] > 1e-9 => {
                        a[1] + (b[1] - a[1]) * (x - a[0]) / (b[0] - a[0])
                    }
                    (Some(a), _) => a[1],
                    (None, Some(b)) => b[1],
                    (None, None) => 0.0,
                }
            }
        }
    }
}

